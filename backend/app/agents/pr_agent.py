import random
from datetime import datetime
from typing import Dict, Any, List
from sqlalchemy.orm import Session
from app.agents.base_agent import BaseAgent
from app.db.models import AgentRun, PullRequestRecord
from app.services.ai_service import ai_service
from app.services.github_service import github_service

class PRAgent(BaseAgent):
    def __init__(self):
        super().__init__(
            agent_name="pr_agent",
            display_name="PR Agent",
            description="Creates authorized git branch, commits verified patch, generates comprehensive PR documentation, and opens Pull Request."
        )

    async def run(self, agent_run: AgentRun, db: Session, context: Dict[str, Any]) -> Dict[str, Any]:
        repo = agent_run.repository
        issue = agent_run.issue
        patch = agent_run.patch
        test_results = context.get("test_result", {})
        
        # 1. Verification Gate: Ensure human patch approval has been granted
        if not patch or not patch.is_approved:
            error_msg = "Cannot open Pull Request: Human patch approval has not been granted."
            self.log(db, agent_run.id, f"ERROR: {error_msg}", level="ERROR")
            raise ValueError(error_msg)

        self.log(db, agent_run.id, f"Preparing Pull Request for repository '{repo.full_name}'...")
        
        system_prompt = (
            "You are the PR Agent AI. Generate a professional Pull Request title and comprehensive Markdown body. "
            "Include summary, changes made, test results, and reference to fixing the issue. "
            "Never suggest automatic merge; emphasize human review."
        )
        user_prompt = (
            f"Generate Pull Request details for issue #{issue.issue_number}: '{issue.title}'\n"
            f"Changes: {patch.change_summary if patch else 'Code fixes'}\n"
            f"Test results: {test_results.get('passed_count', 0)} passed\n"
            f"Head branch: {agent_run.branch_name}\n"
            f"Base branch: {agent_run.base_branch}\n"
        )
        
        pr_details = await ai_service._call_llm_json(system_prompt, user_prompt)
        
        title = pr_details.get("title", f"fix: resolve #{issue.issue_number} - {issue.title}")
        body = pr_details.get("description", f"Resolves #{issue.issue_number}.\n\nAutomated PR generated by Issue to PR Agent.")
        head_branch = agent_run.branch_name
        base_branch = agent_run.base_branch or repo.default_branch or "main"
        
        pr_number = None
        html_url = None
        
        # 2. Branch, Commit, and PR Creation
        if not agent_run.is_demo:
            # LIVE GITHUB MODE: Real GitHub API Operations
            token = github_service.token
            if not token:
                error_msg = (
                    "GitHub Personal Access Token is required to open a real Pull Request. "
                    "Configure GITHUB_TOKEN environment variable or connect your account in Settings."
                )
                self.log(db, agent_run.id, f"ERROR: {error_msg}", level="ERROR")
                raise PermissionError(error_msg)

            # A. Verify access to target repository
            self.log(db, agent_run.id, f"Verifying access to GitHub repository '{repo.full_name}'...")
            try:
                await github_service.get_repository(repo.owner, repo.name)
                self.log(db, agent_run.id, f"Access confirmed for '{repo.full_name}'.")
            except Exception as e:
                error_msg = f"Failed to access GitHub repository '{repo.full_name}': {str(e)}"
                self.log(db, agent_run.id, f"ERROR: {error_msg}", level="ERROR")
                raise PermissionError(error_msg)

            # B. Create the feature branch on GitHub
            self.log(db, agent_run.id, f"Creating branch '{head_branch}' from '{base_branch}' on GitHub...")
            try:
                await github_service.create_branch(repo.owner, repo.name, head_branch, base_branch)
                self.log(db, agent_run.id, f"Branch '{head_branch}' verified on GitHub.")
            except Exception as e:
                error_msg = f"Failed to create branch on GitHub: {str(e)}"
                self.log(db, agent_run.id, f"ERROR: {error_msg}", level="ERROR")
                raise ValueError(error_msg)

            # C. Collect and commit modified files to the branch
            files_to_commit: List[Dict[str, str]] = []
            if patch and patch.files_changed:
                for f in patch.files_changed:
                    path = f.get("file_path")
                    content = f.get("new_content")
                    if path and content:
                        files_to_commit.append({"path": path, "content": content})

            if not files_to_commit:
                error_msg = "No file contents found in patch to commit."
                self.log(db, agent_run.id, f"ERROR: {error_msg}", level="ERROR")
                raise ValueError(error_msg)

            self.log(db, agent_run.id, f"Committing {len(files_to_commit)} modified file(s) to branch '{head_branch}'...")
            try:
                commit_msg = f"fix: resolve #{issue.issue_number} - {issue.title}\n\nAutomated fix generated by Issue to PR Agent"
                commit_res = await github_service.commit_files(
                    owner=repo.owner,
                    repo=repo.name,
                    branch_name=head_branch,
                    files=files_to_commit,
                    commit_message=commit_msg
                )
                commit_sha = commit_res.get("commit_sha", "")[:7]
                self.log(db, agent_run.id, f"Successfully committed patch to GitHub branch '{head_branch}' (commit: {commit_sha})")
            except Exception as e:
                error_msg = f"Failed to commit patch to GitHub branch: {str(e)}"
                self.log(db, agent_run.id, f"ERROR: {error_msg}", level="ERROR")
                raise ValueError(error_msg)

            # D. Submit real Pull Request via GitHub REST API
            self.log(db, agent_run.id, f"Submitting Pull Request via GitHub REST API to '{base_branch}'...")
            try:
                pr_response = await github_service.create_pull_request(
                    owner=repo.owner,
                    repo=repo.name,
                    title=title,
                    body=body,
                    head_branch=head_branch,
                    base_branch=base_branch
                )
                pr_number = pr_response.get("number")
                html_url = pr_response.get("html_url")
                self.log(db, agent_run.id, f"VERIFIED: Real GitHub Pull Request #{pr_number} created successfully: {html_url}")
            except Exception as e:
                error_msg = f"Failed to open Pull Request on GitHub: {str(e)}"
                self.log(db, agent_run.id, f"ERROR: {error_msg}", level="ERROR")
                raise ValueError(error_msg)
        else:
            # DEMO MODE SIMULATION: Safe Offline Sandbox Mock
            pr_number = random.randint(101, 199)
            html_url = f"https://github.com/{repo.full_name}/pull/{pr_number}"
            self.log(db, agent_run.id, f"[DEMO MODE SIMULATION] Generated simulated Pull Request #{pr_number} locally.")
            self.log(db, agent_run.id, "NOTE: Demo mode operates offline in a sandbox. No remote branches or PRs are created on GitHub.")
            
        # 3. Persist PullRequestRecord in database
        existing_pr = db.query(PullRequestRecord).filter(PullRequestRecord.agent_run_id == agent_run.id).first()
        if existing_pr:
            existing_pr.title = title
            existing_pr.description = body
            existing_pr.pr_number = pr_number
            existing_pr.html_url = html_url
            existing_pr.head_branch = head_branch
            existing_pr.base_branch = base_branch
            existing_pr.is_approved = True
            existing_pr.approved_at = datetime.utcnow()
            existing_pr.is_demo = agent_run.is_demo
        else:
            pr_record = PullRequestRecord(
                agent_run_id=agent_run.id,
                repository_id=repo.id,
                pr_number=pr_number,
                title=title,
                description=body,
                html_url=html_url,
                head_branch=head_branch,
                base_branch=base_branch,
                state="open",
                checks_passing=True,
                is_approved=True,
                approved_at=datetime.utcnow(),
                is_demo=agent_run.is_demo,
                created_at=datetime.utcnow()
            )
            db.add(pr_record)
            
        db.commit()
        
        self.log(db, agent_run.id, f"Pull Request ready for human code review. PR URL: {html_url}")
        self.log(db, agent_run.id, "NOTE: Automatic merge is disabled by design. A human maintainer must review and merge on GitHub.")
        
        return {
            "pr_number": pr_number,
            "title": title,
            "html_url": html_url,
            "head_branch": head_branch,
            "base_branch": base_branch,
            "is_demo": agent_run.is_demo
        }

pr_agent = PRAgent()
